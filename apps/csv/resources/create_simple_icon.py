"""Create a simple ICO file from a 1x1 colored pixel (fallback)."""
import struct
from pathlib import Path

# Create a minimal valid ICO file (1x1 blue pixel)
# This is the smallest valid ICO: one 1x1 image with 1 BPP (blue/white)
ico_data = bytes([
    0x00, 0x00,  # Reserved
    0x01, 0x00,  # Number of images
    0x01, 0x00,  # Width
    0x01, 0x00,  # Height
    0x00,        # Color count
    0x00,        # Reserved
    0x01, 0x00,  # Color planes
    0x20, 0x00,  # Bits per pixel
    0x30, 0x00, 0x00, 0x00,  # Image data size
    0x16, 0x00, 0x00, 0x00,  # Image data offset
    # BMP image data (1x1 pixel at offset 0x16)
    0x28, 0x00, 0x00, 0x00,  # BMP header size
    0x01, 0x00, 0x00, 0x00,  # Width
    0x02, 0x00, 0x00, 0x00,  # Height (doubled for ICO)
    0x01, 0x00,              # Planes
    0x20, 0x00,              # BPP
    0x00, 0x00, 0x00, 0x00,  # Compression
    0x08, 0x00, 0x00, 0x00,  # Image size
    0x00, 0x00, 0x00, 0x00,  # H resolution
    0x00, 0x00, 0x00, 0x00,  # V resolution
    0x00, 0x00, 0x00, 0x00,  # Colors used
    0x00, 0x00, 0x00, 0x00,  # Colors important
    # 1x1 pixel: blue (BGRA format)
    0x00, 0x55, 0x91, 0xFF,  # Blue pixel
    # AND mask
    0x00, 0x00, 0x00, 0x00,
])

icon_path = Path(__file__).parent / "app.ico"
icon_path.write_bytes(ico_data)
print(f"[OK] Generated {icon_path}")
